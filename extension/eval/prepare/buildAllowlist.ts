/**
 * Build the top-sites allow-list from a Tranco list.
 *
 *   npm run prepare:allowlist                 (defaults: top 10,000 of data/raw/tranco/top-1m.csv)
 *   npm run prepare:allowlist -- --top=5000
 *
 * Writes src/shared/data/allowlist.generated.ts. The source list ID, date,
 * sha256 and N are embedded so the exact list used is documented.
 *
 * Domains whose content is written by arbitrary users (site builders, file
 * hosting, form builders, IPFS gateways, URL shorteners) are EXCLUDED —
 * attackers routinely host phishing on them, so "popular" ≠ "trustworthy".
 * Most such platforms are already separated by the PSL private section
 * (evil.github.io ≠ github.io); this list covers the rest.
 */

import * as fs from "fs";
import * as path from "path";
import { getDomain } from "tldts";
import { parseCsv } from "../lib/csv";
import { EVAL_DIR, EXT_DIR, loadDatasetRegistry, parseArgs, sha256File } from "../lib/common";

export const USER_CONTENT_EXCLUSIONS = [
  // Google user content
  "sites.google.com", "docs.google.com", "drive.google.com", "script.google.com", "forms.gle",
  "storage.googleapis.com", "firebasestorage.googleapis.com", "googleusercontent.com", "web.app", "firebaseapp.com",
  // Microsoft user content
  "sharepoint.com", "onedrive.live.com", "1drv.ms", "azurewebsites.net", "blob.core.windows.net", "web.core.windows.net",
  // File hosting / sharing
  "dropbox.com", "dropboxusercontent.com", "box.com", "wetransfer.com", "mediafire.com", "mega.nz",
  // Site builders / hosting
  "weebly.com", "wixsite.com", "wix.com", "webflow.io", "square.site", "godaddysites.com", "mystrikingly.com",
  "jimdosite.com", "000webhostapp.com", "netlify.app", "vercel.app", "pages.dev", "workers.dev", "herokuapp.com",
  "github.io", "gitlab.io", "blogspot.com", "wordpress.com", "tumblr.com", "glitch.me", "repl.co", "notion.site",
  "canva.site", "framer.website", "carrd.co", "ngrok.io", "ngrok-free.app", "myqcloud.com", "r2.dev",
  // Forms / surveys
  "typeform.com", "jotform.com", "surveymonkey.com", "formstack.com",
  // IPFS gateways
  "ipfs.io", "cloudflare-ipfs.com", "dweb.link", "pinata.cloud",
  // URL shorteners
  "bit.ly", "tinyurl.com", "t.co", "goo.gl", "ow.ly", "is.gd", "cutt.ly", "rebrand.ly", "shorturl.at", "rb.gy", "t.ly", "tiny.cc", "buff.ly",
];

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const top = Number(args.get("top") ?? 10000);
  const meta = loadDatasetRegistry().tranco;
  const file = path.resolve(EVAL_DIR, meta.file);
  if (!fs.existsSync(file)) throw new Error(`Tranco list not found at ${file}. Download ${meta.downloadUrl} and unzip it there.`);
  const sha = sha256File(file);

  const excluded = new Set(USER_CONTENT_EXCLUSIONS);
  const out: string[] = [];
  const seen = new Set<string>();
  let considered = 0;
  let droppedExcluded = 0;
  let droppedNoDomain = 0;

  parseCsv(fs.readFileSync(file, "utf-8"), (fields) => {
    if (considered >= top) return;
    considered++;
    const raw = (fields[1] ?? "").trim().toLowerCase();
    const reg = getDomain(raw, { allowPrivateDomains: true });
    if (!reg) { droppedNoDomain++; return; }
    if (excluded.has(reg) || excluded.has(raw)) { droppedExcluded++; return; }
    if (seen.has(reg)) return;
    seen.add(reg);
    out.push(reg);
  });

  const metaOut = {
    source: "Tranco",
    listId: meta.listId ?? "unknown",
    listUrl: meta.sourceUrl,
    downloadedAt: meta.downloadedAt ?? "unknown",
    sha256: sha,
    topN: top,
    size: out.length,
    excludedUserContent: droppedExcluded,
    droppedNoRegistrableDomain: droppedNoDomain,
    description: `Tranco ${meta.listId} top ${top} (${out.length} registrable domains; user-content hosts and shorteners excluded)`,
  };

  const dest = path.join(EXT_DIR, "src", "shared", "data", "allowlist.generated.ts");
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(
    dest,
    `/* AUTO-GENERATED by eval/prepare/buildAllowlist.ts — do not edit by hand. */\n` +
      `export const ALLOWLIST_GENERATED_META = ${JSON.stringify(metaOut, null, 2)} as const;\n\n` +
      `export const ALLOWLIST_EXCLUSIONS: readonly string[] = ${JSON.stringify(USER_CONTENT_EXCLUSIONS)};\n\n` +
      `export const ALLOWLIST_DOMAINS_PACKED = ${JSON.stringify(out.join(" "))};\n`
  );
  console.log(`Wrote ${dest}\n${JSON.stringify(metaOut, null, 2)}`);
}

main();
