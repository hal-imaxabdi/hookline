/**
 * Generate docs/RULES.md from the rule registry, so the paper can cite rule
 * IDs, weights and descriptions that are guaranteed to match the code.
 *
 *   npm run rules:doc
 */
import * as fs from "fs";
import * as path from "path";
import { RULES, ALL_RULE_IDS, rulesetFingerprint, type RuleDef } from "../src/shared/ruleRegistry";
import { SEVERITY_FACTOR, HIGH_RISK_AT, SUSPICIOUS_AT, CATEGORY_MIN_POINTS } from "../src/shared/riskEngine";
import { ALLOWLIST_META } from "../src/shared/allowlist";
import { HOOKLINE_VERSION } from "../src/shared/version";
import { EXT_DIR } from "./lib/common";

const CATS: Array<[RuleDef["category"], string]> = [
  ["credential_phishing", "Credential phishing"],
  ["job_scam", "Job / internship scam"],
  ["shopping_scam", "Shopping scam"],
  ["general", "General (raises risk, never names a category)"],
];

const esc = (s: string) => s.replace(/\|/g, "\\|");

const L: string[] = [];
L.push("# Hookline detection rules", "");
L.push(`_Generated by \`npm run rules:doc\` from \`extension/src/shared/ruleRegistry.ts\` — Hookline ${HOOKLINE_VERSION}, ruleset fingerprint \`${rulesetFingerprint()}\`. Do not edit by hand._`, "");
L.push("## Scoring", "");
L.push(`- Each rule has a **weight** (points at *high* severity). Severity factors: high ${SEVERITY_FACTOR.high}, medium ${SEVERITY_FACTOR.medium}, low ${SEVERITY_FACTOR.low}.`);
L.push("- Rules belong to a **group**; only the strongest item per group counts, and groups add up. Score = min(100, Σ group maxima).");
L.push(`- Verdict: **high risk** ≥ ${HIGH_RISK_AT}, **suspicious** ≥ ${SUSPICIOUS_AT}, otherwise safe.`);
L.push(`- Category: the scam category with the most points (≥ ${CATEGORY_MIN_POINTS}) among non-"general" rules, if the verdict isn't safe; otherwise "None detected".`);
L.push(`- **Allow-list** (${ALLOWLIST_META.description}): rules marked "AL" are ignored on allow-listed domains.`, "");

for (const [cat, label] of CATS) {
  const ids = ALL_RULE_IDS.filter((id) => RULES[id].category === cat);
  if (!ids.length) continue;
  L.push(`## ${label}`, "");
  L.push("| ID | Group | Weight | Default severity (points) | Scope | AL | What it means | Source |");
  L.push("|---|---|---|---|---|---|---|---|");
  for (const id of ids) {
    const r = RULES[id];
    const pts = r.weight * SEVERITY_FACTOR[r.defaultSeverity];
    L.push(`| \`${id}\` | ${r.group} | ${r.weight} | ${r.defaultSeverity} (${pts}) | ${r.scope.join(", ")} | ${r.allowlistSuppressible ? "✓" : ""} | **${esc(r.title)}.** ${esc(r.description)} | ${r.source ? esc(r.source) : ""} |`);
  }
  L.push("");
}

const out = path.resolve(EXT_DIR, "..", "docs", "RULES.md");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join("\n"));
console.log(`Wrote ${out} (${ALL_RULE_IDS.length} rules, fingerprint ${rulesetFingerprint()})`);
